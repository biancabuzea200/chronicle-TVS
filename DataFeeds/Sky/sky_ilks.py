#!/usr/bin/env python3
"""
Sources Sky (formerly MakerDAO) collateral data AND its USD valuation
entirely from Sky's own on-chain contracts -- no DefiLlama, no CoinGecko --
for Component 2 (Data Feeds TVS).

Why not DefiLlama: its Chronicle oracle page returns HTTP 403 to automated
fetches, its numbers for Sky don't reconcile cleanly against the raw
protocol data (see README.md), and its "oraclesBreakdown" for Sky Lending's
Chronicle tag ships with an empty proof array. Same philosophy as
../morpho/morpho_markets.py: go straight to the protocol's own source of
truth.

How it works:
  1. Sky's `Chainlog` contract is the canonical, upgradeable registry of
     every system contract address (always at the same address itself).
     From it we resolve `ILK_REGISTRY`, `MCD_VAT`, and `MCD_SPOT`.
  2. `IlkRegistry.list()` enumerates every active ilk (collateral type).
     `IlkRegistry.{pip,gem,join}(ilk)` give each ilk's price oracle
     (`pip`), collateral token, and the adapter holding locked collateral
     (`join`).
  3. Each `pip` is normally an OSM (Oracle Security Module) with a public
     `src()` getter pointing to the underlying price feed it reads from
     (a Chronicle Scribe, a legacy Median, or something else). `src()`/`pip`
     is compared against KNOWN_CHRONICLE_ADDRESSES -- confirmed via Sky's
     March 20, 2025 executive spell migrating ETH/wstETH oracles to
     Chronicle's Scribe design (see README.md for the governance links).
     Anything else is reported as "unverified" rather than guessed.

     NOTE on scope: per an explicit decision recorded in README.md, this
     repo treats *every* Sky Lending ilk as Chronicle-powered for Component
     2 purposes, not just the governance-confirmed ones above -- the
     is_chronicle/KNOWN_CHRONICLE_ADDRESSES machinery is kept and computed
     because it's real, useful evidence, but it no longer gates what counts
     toward the overview CSV's total.
  4. Collateral locked per ilk = token balance at `join` (read via
     `balanceOf`), in raw token units.
  5. USD price per ilk comes from Sky's OWN risk-engine accounting, not an
     external price source: `Vat.ilks(ilk).spot` (price with safety margin,
     [ray]) and `Spot.ilks(ilk).mat` (liquidation ratio, [ray]) and
     `Spot.par()` (DAI peg, [ray]) combine via the exact formula in
     `Spotter.poke()` (github.com/makerdao/dss/blob/master/src/spot.sol):
         spot = ((price * 1e9) / par) / mat     [all rdiv, i.e. x*1e27/y]
     Inverting: price = spot * par * mat / 1e63 (WAD, 1e18). This is
     readable by anyone (no `toll` gate, unlike the OSM's `peek()`/`read()`)
     because Spot itself already called peek() when it last poked the
     price -- we're just reading what Sky's own system already stored.
     Verified against live spot prices for ETH/WBTC/wstETH before trusting
     it, and it notably also resolves RWA ilks' real face value (something
     no public price API provides at all).

Usage:
    pip install requests pycryptodome
    python3 sky_ilks.py
    python3 sky_ilks.py --rpc https://your-rpc-url --csv out.csv --json out.json
"""

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests
from Crypto.Hash import keccak

DEFAULT_RPC = "https://ethereum-rpc.publicnode.com"
CHAINLOG = "0xdA0Ab1e0017DEbCd72Be8599041a2aa3bA7e740F"
# Last-verified fallbacks if a Chainlog lookup ever fails -- normally resolved live.
ILK_REGISTRY = "0x5a464C28D19848f44199D003BeF5ecc87d090F87"
MCD_VAT = "0x35D1b3F3D7966A1DFe207aa4514C12a259A0492B"
MCD_SPOT = "0x65C79fcB50Ca1594B025960e539eD7A9a6D434A3"

DEFAULT_CSV_PATH = Path(__file__).parent / "sky_ilks.csv"
DEFAULT_JSON_PATH = Path(__file__).parent / "sky_ilks.json"
DEFAULT_OVERVIEW_CSV_PATH = Path(__file__).parent / "sky_chronicle_overview.csv"
# Standard cross-protocol total file -- see ../chronicle_total_tvs.py, which sums
# this same filename across every DataFeeds/<protocol>/ folder. Never hand-edit;
# always regenerated by this script.
DEFAULT_TOTAL_PATH = Path(__file__).parent / "chronicle_total.json"

# ilks on Sky's newer "Allocator" vault system, which doesn't register a
# gem/join in IlkRegistry the classic way -- Vat/Spot still price them (all
# resolve to exactly $1.00, being stablecoin-denominated), but the locked
# collateral AMOUNT isn't obtainable via this script's balanceOf-at-join
# approach, so they're flagged rather than guessed.
ALLOCATOR_ILKS = {
    "ALLOCATOR-SPARK-A", "ALLOCATOR-GROVE-A", "ALLOCATOR-NOVA-A", "ALLOCATOR-BLOOM-A",
    "ALLOCATOR-INTERVAL-A", "ALLOCATOR-OBEX-A", "ALLOCATOR-PATTERN-A", "ALLOCATOR-PRYSM-A",
}

# Confirmed via Sky's March 20, 2025 executive spell (OsmAbstract(PIP_ETH/PIP_WSTETH).change(...))
# -- see README.md for the governance vote + forum links. Anything not in this
# dict is reported as "unverified", never silently assumed to be Chronicle.
KNOWN_CHRONICLE_ADDRESSES = {
    "0x46ef0071b1e2ff6b42d36e5a177ea43ae5917f4e": "Chronicle Scribe (ETH/USD, per Mar 20 2025 spell)",
    "0xa770582353b573cbfdcc948751750eeb3ccf23cf": "Chronicle Scribe (wstETH/USD, per Mar 20 2025 spell)",
}


def keccak_selector(signature: str) -> str:
    k = keccak.new(digest_bits=256)
    k.update(signature.encode())
    return k.hexdigest()[:8]


SEL = {
    "resolve(bytes32)": keccak_selector("getAddress(bytes32)"),  # Chainlog's actual getter
    "list()": keccak_selector("list()"),
    "pip(bytes32)": keccak_selector("pip(bytes32)"),
    "gem(bytes32)": keccak_selector("gem(bytes32)"),
    "join(bytes32)": keccak_selector("join(bytes32)"),
    "src()": keccak_selector("src()"),
    "wat()": keccak_selector("wat()"),
    "balanceOf(address)": keccak_selector("balanceOf(address)"),
    "decimals()": keccak_selector("decimals()"),
    "symbol()": keccak_selector("symbol()"),
    "vat_ilks(bytes32)": keccak_selector("ilks(bytes32)"),  # same text selector on both Vat and Spot (different ABIs)
    "par()": keccak_selector("par()"),
    "pocket()": keccak_selector("pocket()"),
}


def rpc_call(rpc_url: str, to: str, data: str):
    resp = requests.post(
        rpc_url,
        json={"jsonrpc": "2.0", "method": "eth_call", "params": [{"to": to, "data": data}, "latest"], "id": 1},
        timeout=20,
    )
    resp.raise_for_status()
    j = resp.json()
    if "error" in j:
        return None
    return j.get("result")


def addr_from_word(hexres):
    if not hexres or len(hexres) < 66:
        return None
    addr = "0x" + hexres[-40:]
    return addr if int(addr, 16) != 0 else None


def uint_from_word(hexres):
    if not hexres:
        return None
    return int(hexres, 16)


def words(hexres):
    h = hexres[2:]
    return [h[i : i + 64] for i in range(0, len(h), 64)]


def decode_bytes32_array(hexres):
    w = words(hexres)
    length = int(w[1], 16)
    return ["0x" + x for x in w[2 : 2 + length]]


def decode_string(hexres):
    try:
        w = words(hexres)
        length = int(w[1], 16)
        data = bytes.fromhex("".join(w[2:]))[:length]
        return data.decode("utf-8", errors="replace")
    except Exception:
        return None


def bytes32_to_name(ilk_hex: str) -> str:
    raw = bytes.fromhex(ilk_hex[2:])
    return raw.rstrip(b"\x00").decode("latin1", errors="replace")


def resolve_from_chainlog(rpc_url, key, fallback, quiet=False):
    key_hex = key.encode().ljust(32, b"\x00").hex()
    resolved = addr_from_word(rpc_call(rpc_url, CHAINLOG, "0x" + SEL["resolve(bytes32)"] + key_hex))
    if not resolved:
        if not quiet:
            print(f"  Chainlog lookup for {key} failed, falling back to last-verified address {fallback}", file=sys.stderr)
        return fallback
    return resolved


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rpc", default=DEFAULT_RPC, help=f"Ethereum JSON-RPC endpoint (default: {DEFAULT_RPC})")
    parser.add_argument("--csv", default=str(DEFAULT_CSV_PATH), help=f"write per-ilk CSV to this path (default: {DEFAULT_CSV_PATH})")
    parser.add_argument("--json", default=str(DEFAULT_JSON_PATH), help=f"write full JSON to this path (default: {DEFAULT_JSON_PATH})")
    parser.add_argument(
        "--overview-csv",
        default=str(DEFAULT_OVERVIEW_CSV_PATH),
        help=f"write the human-readable USD summary (all ilks) to this path (default: {DEFAULT_OVERVIEW_CSV_PATH})",
    )
    parser.add_argument(
        "--total-json",
        default=str(DEFAULT_TOTAL_PATH),
        help=f"write the standard cross-protocol total file to this path (default: {DEFAULT_TOTAL_PATH})",
    )
    parser.add_argument("--no-output", action="store_true", help="skip writing --csv/--json/--overview-csv/--total-json files")
    args = parser.parse_args()
    if args.no_output:
        args.csv = None
        args.json = None
        args.overview_csv = None
        args.total_json = None

    print("Resolving system contracts from Chainlog...", file=sys.stderr)
    ilk_registry = resolve_from_chainlog(args.rpc, "ILK_REGISTRY", ILK_REGISTRY)
    vat = resolve_from_chainlog(args.rpc, "MCD_VAT", MCD_VAT)
    spot = resolve_from_chainlog(args.rpc, "MCD_SPOT", MCD_SPOT)
    print(f"  IlkRegistry={ilk_registry}  Vat={vat}  Spot={spot}", file=sys.stderr)

    par = uint_from_word(rpc_call(args.rpc, spot, "0x" + SEL["par()"]))
    print(f"  Spot.par()={par}", file=sys.stderr)

    ilks_raw = decode_bytes32_array(rpc_call(args.rpc, ilk_registry, "0x" + SEL["list()"]))
    print(f"{len(ilks_raw)} active ilk(s) found. Reading pip/gem/join/src and Vat/Spot pricing for each...", file=sys.stderr)

    results = []
    for ilk_hex in ilks_raw:
        name = bytes32_to_name(ilk_hex)
        ilk_arg = ilk_hex[2:].ljust(64, "0")

        pip = addr_from_word(rpc_call(args.rpc, ilk_registry, "0x" + SEL["pip(bytes32)"] + ilk_arg))
        gem = addr_from_word(rpc_call(args.rpc, ilk_registry, "0x" + SEL["gem(bytes32)"] + ilk_arg))
        join = addr_from_word(rpc_call(args.rpc, ilk_registry, "0x" + SEL["join(bytes32)"] + ilk_arg))

        src = None
        if pip:
            src_res = rpc_call(args.rpc, pip, "0x" + SEL["src()"])
            src = addr_from_word(src_res) if src_res else None

        oracle_addr = (src or pip or "").lower()
        chronicle_note = KNOWN_CHRONICLE_ADDRESSES.get(oracle_addr)
        is_chronicle = chronicle_note is not None

        wat = None
        if oracle_addr and not is_chronicle:
            wat_res = rpc_call(args.rpc, oracle_addr, "0x" + SEL["wat()"])
            if wat_res and int(wat_res, 16) != 0:
                wat = bytes.fromhex(wat_res[2:]).rstrip(b"\x00").decode("latin1", errors="replace")

        gem_symbol, gem_decimals, locked_tokens = None, None, None
        if gem:
            sym_res = rpc_call(args.rpc, gem, "0x" + SEL["symbol()"])
            gem_symbol = decode_string(sym_res) if sym_res else None
            dec_res = rpc_call(args.rpc, gem, "0x" + SEL["decimals()"])
            gem_decimals = uint_from_word(dec_res) if dec_res else 18

            balance_holder = join
            if balance_holder is None:
                # Some newer modules (e.g. DssLitePsm) don't register a classic
                # `join` in IlkRegistry at all -- they hold `gem` in a separate
                # `pocket` contract instead, resolved via Chainlog using the
                # module's own name (Chainlog key "MCD_" + ilk name with "-" -> "_",
                # e.g. ilk "LITE-PSM-USDC-A" -> module "MCD_LITE_PSM_USDC_A").
                module_key = "MCD_" + name.replace("-", "_")
                module_addr = resolve_from_chainlog(args.rpc, module_key, None, quiet=True)
                if module_addr:
                    pocket_res = rpc_call(args.rpc, module_addr, "0x" + SEL["pocket()"])
                    balance_holder = addr_from_word(pocket_res) if pocket_res else None

            if balance_holder:
                bal_arg = balance_holder[2:].rjust(64, "0")
                bal_res = rpc_call(args.rpc, gem, "0x" + SEL["balanceOf(address)"] + bal_arg)
                locked_raw = uint_from_word(bal_res)
                if locked_raw is not None:
                    locked_tokens = locked_raw / (10 ** gem_decimals)

        # Sky's own system price for this ilk (see docstring for the formula/source).
        price_usd = None
        vat_res = rpc_call(args.rpc, vat, "0x" + SEL["vat_ilks(bytes32)"] + ilk_arg)
        spot_res = rpc_call(args.rpc, spot, "0x" + SEL["vat_ilks(bytes32)"] + ilk_arg)
        if vat_res and spot_res and par:
            vat_spot = int(words(vat_res)[2], 16)  # Vat.Ilk.spot
            mat = int(words(spot_res)[1], 16)  # Spotter.Ilk.mat
            if vat_spot and mat:
                price_usd = (vat_spot * par * mat) / (10 ** 63) / 1e18

        value_usd = locked_tokens * price_usd if (locked_tokens is not None and price_usd is not None) else None

        results.append(
            {
                "ilk": name,
                "pip": pip,
                "src": src,
                "oracleAddress": src or pip,
                "isChronicle": is_chronicle,
                "chronicleNote": chronicle_note,
                "wat": wat,
                "gem": gem,
                "gemSymbol": gem_symbol,
                "join": join,
                "lockedTokens": locked_tokens,
                "priceUsd": price_usd,
                "valueUsd": value_usd,
            }
        )
        flag = "CHRONICLE" if is_chronicle else ("no-oracle" if not oracle_addr else f"unverified{' (' + wat + ')' if wat else ''}")
        price_str = f"${price_usd:,.4f}" if price_usd is not None else "?"
        locked_str = f"{locked_tokens:,.4f}" if locked_tokens is not None else "?"
        print(f"  {name:28s} gem={gem_symbol or '?':10s} locked={locked_str:>18s}  price={price_str:>16s}  oracle={oracle_addr or '-':42s} [{flag}]", file=sys.stderr)

    chronicle_ilks = [r for r in results if r["isChronicle"]]
    priced = [r for r in results if r["valueUsd"] is not None]
    grand_total = sum(r["valueUsd"] for r in priced)
    print(f"\n{len(chronicle_ilks)}/{len(results)} ilk(s) governance-confirmed Chronicle-sourced (ETH-A/B/C, WSTETH-A/B).")
    print(f"{len(priced)}/{len(results)} ilk(s) fully priced via Sky's own Vat/Spot accounting -- total ${grand_total:,.2f}.")
    print("(Per README.md, every ilk here counts toward Component 2 regardless of the Chronicle-confirmation flag above.)")

    if args.csv:
        import csv

        with open(args.csv, "w", newline="") as fh:
            writer = csv.writer(fh)
            writer.writerow(
                [
                    "ilk", "gem_symbol", "locked_tokens", "price_usd", "value_usd",
                    "oracle_address", "is_chronicle", "chronicle_note", "unverified_oracle_wat",
                    "pip", "src", "gem", "join",
                ]
            )
            for r in results:
                writer.writerow(
                    [
                        r["ilk"],
                        r["gemSymbol"] or "",
                        f"{r['lockedTokens']:.6f}" if r["lockedTokens"] is not None else "",
                        f"{r['priceUsd']:.6f}" if r["priceUsd"] is not None else "",
                        f"{r['valueUsd']:.2f}" if r["valueUsd"] is not None else "",
                        r["oracleAddress"] or "",
                        r["isChronicle"],
                        r["chronicleNote"] or "",
                        r["wat"] or "",
                        r["pip"] or "",
                        r["src"] or "",
                        r["gem"] or "",
                        r["join"] or "",
                    ]
                )
        print(f"\nWrote {args.csv}", file=sys.stderr)

    if args.json:
        with open(args.json, "w") as fh:
            json.dump({"ilkRegistry": ilk_registry, "vat": vat, "spot": spot, "par": par, "ilks": results}, fh, indent=2)
        print(f"Wrote {args.json}", file=sys.stderr)

    grand_total = None
    if args.overview_csv:
        grand_total = write_overview_csv(results, args.overview_csv)

    if args.total_json:
        if grand_total is None:
            # --overview-csv was skipped but --total-json wasn't -- compute the
            # same total without writing the CSV.
            grand_total = sum(
                r["lockedTokens"] * r["priceUsd"]
                for r in results
                if r["ilk"] not in ALLOCATOR_ILKS and r["lockedTokens"] is not None and r["priceUsd"] is not None
            )
        write_total_json(grand_total, args.overview_csv, args.total_json)


def write_total_json(total_usd: float, breakdown_file: str, path: str):
    """Standard cross-protocol total file -- see ../chronicle_total_tvs.py."""
    with open(path, "w") as fh:
        json.dump(
            {
                "protocol": "Sky",
                "totalUsd": round(total_usd, 2),
                "generatedAt": datetime.now(timezone.utc).isoformat(),
                "breakdownFile": Path(breakdown_file).name if breakdown_file else None,
            },
            fh,
            indent=2,
        )
    print(f"Wrote {path}", file=sys.stderr)


def write_overview_csv(all_ilks: list, path: str) -> float:
    """Full breakdown of Sky Lending ilks, priced via Sky's own Vat/Spot
    accounting (see module docstring). Per explicit scope decisions in
    README.md: every ilk here counts toward Component 2 regardless of
    individual Chronicle proof, EXCEPT the Allocator-system ilks, which are
    deliberately excluded -- they're Sky-minted DAI/USDS deployed into other
    systems (Spark, Grove, etc.), tracked separately, not Sky Lending
    collateral in the traditional sense. This function prices what it can
    and is honest (via `note`) about what it can't, never guesses."""
    import csv

    rows = []
    for r in all_ilks:
        if r["ilk"] in ALLOCATOR_ILKS:
            continue  # tracked separately -- see README.md
        note = ""
        if r["valueUsd"] is None:
            if r["priceUsd"] is None:
                note = "Spot/Vat price not configured for this ilk (mat or spot == 0) -- likely inactive/deprecated module"
            elif r["lockedTokens"] is None:
                note = f"{r['gemSymbol'] or 'collateral'} balance not resolved (join lookup failed) -- needs investigation"
        rows.append(
            {
                "ilk": r["ilk"],
                "gem": r["gemSymbol"] or "",
                "locked_tokens": r["lockedTokens"],
                "price_usd": r["priceUsd"],
                "value_usd": r["valueUsd"],
                "note": note,
            }
        )

    priced = [r for r in rows if r["value_usd"] is not None]
    unresolved = [r for r in rows if r["value_usd"] is None]
    grand_total = sum(r["value_usd"] for r in priced)

    with open(path, "w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["ilk", "gem", "locked_tokens", "price_usd", "value_usd", "note"])
        for r in sorted(rows, key=lambda x: x["value_usd"] or -1, reverse=True):
            writer.writerow(
                [
                    r["ilk"],
                    r["gem"],
                    f"{r['locked_tokens']:.6f}" if r["locked_tokens"] is not None else "",
                    f"{r['price_usd']:.6f}" if r["price_usd"] is not None else "",
                    f"{r['value_usd']:.2f}" if r["value_usd"] is not None else "",
                    r["note"],
                ]
            )
        writer.writerow(["TOTAL (priced ilks only)", "", "", "", f"{grand_total:.2f}", f"{len(unresolved)} ilk(s) not yet priced -- see notes"])
    print(f"Wrote {path} (priced total: ${grand_total:,.2f} across {len(priced)} ilks; {len(unresolved)} unresolved)", file=sys.stderr)
    return grand_total


if __name__ == "__main__":
    main()
