#!/usr/bin/env python3
"""
For each Morpho market identified as powered by Chronicle's oracle (see
morpho_markets.py / morpho_chronicle_history.json), traces the market's
suppliers back to a curator -- e.g. "Steakhouse Financial: $X across N
markets" -- by classifying every significant supplier address as one of:

  - a MetaMorpho ("V1") vault             -> attributed to that vault's curator
  - a MetaMorpho V2 ("V2") vault adapter   -> attributed to that vault's curator
  - an unidentified address                -> left unattributed, address kept
                                               in the output for manual lookup

Why this is needed, and why it's NOT as simple as "sum what each vault
allocates": a market's top suppliers (by `marketPositions`, Morpho's public
GraphQL API) are often NOT the vault itself -- for the newer VaultV2
architecture, a vault's capital reaches a market through a separate
"adapter" contract (one per market the vault allocates into), and that
adapter -- not the vault -- is what shows up as the supplier on-chain. A
vault called "Steakhouse Prime ETH" might never appear directly; its
adapter (e.g. 0xA6b6...) does, and only Morpho's `vaultV2s(...).adapters`
data reveals which vault that adapter belongs to. Earlier versions of this
script only checked V1 vault allocations and so miscounted these as "direct
supply with no curator" -- they are not; they were just unresolved V2
adapters. This version resolves both V1 vaults and V2 adapters.

A vault/adapter whose owning vault has no curator formally tagged in
Morpho's registry is matched against the list of known curators (`curators`
query) by name -- e.g. a vault named "Steakhouse High Yield AUSD" gets
attributed to "Steakhouse Financial" because "Steakhouse" appears in both.
This is a heuristic, not an on-chain fact, so it's marked
`"attribution": "inferred-from-name"` (vs. `"tagged"`) and flagged with a
`~` in the printed tables.

Any supplier address that matches neither a V1 vault nor a V2 adapter is
left as "(unidentified address: 0x...)" -- not silently folded into a
generic "direct supply" bucket -- so it stays a concrete, investigable lead
rather than disappearing into a lump sum.

Every run writes its results to morpho_curator_breakdown.json and
morpho_curator_breakdown.csv (next to this script, overwritten each run) --
pass --json/--csv for different paths, or --no-output to skip writing.

Usage:
    pip install requests
    python3 morpho_curators.py
    python3 morpho_curators.py --markets /path/to/morpho_chronicle_history.json
    python3 morpho_curators.py --json curator_breakdown.json --csv curator_breakdown.csv
"""

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

import requests

MIN_WORD_MATCH_LEN = 4  # don't match on short/generic single-word curator names (e.g. "Re", "K3")
TOP_SUPPLIERS_PER_MARKET = 100  # positions fetched per market, ordered by supply desc

DEFAULT_MARKETS_PATH = Path(__file__).parent / "morpho_chronicle_history.json"
DEFAULT_JSON_PATH = Path(__file__).parent / "morpho_curator_breakdown.json"
DEFAULT_CSV_PATH = Path(__file__).parent / "morpho_curator_breakdown.csv"
DEFAULT_OVERVIEW_CSV_PATH = Path(__file__).parent / "morpho_curator_overview.csv"
# Standard cross-protocol total file -- see ../chronicle_total_tvs.py, which sums
# this same filename across every DataFeeds/<protocol>/ folder. Never hand-edit;
# always regenerated by this script.
DEFAULT_TOTAL_PATH = Path(__file__).parent / "chronicle_total.json"
GRAPHQL_URL = "https://blue-api.morpho.org/graphql"


def gql(query: str) -> dict:
    resp = requests.post(GRAPHQL_URL, json={"query": query}, timeout=30)
    resp.raise_for_status()
    data = resp.json()
    if "errors" in data:
        raise RuntimeError(data["errors"])
    return data


def load_chronicle_markets(path: Path) -> list:
    with open(path) as fh:
        history = json.load(fh)
    return [m for m in history["markets"].values() if m.get("currentlyListed", True)]


def fetch_market_chain_and_asset(market_ids: list) -> dict:
    """marketId -> {chainId, loanAssetAddress}. Batched into one query."""
    id_list = ",".join(f'"{m}"' for m in market_ids)
    q = f"""{{
      markets(first:{len(market_ids)}, where:{{uniqueKey_in:[{id_list}]}}) {{
        items {{ marketId loanAsset {{ address }} morphoBlue {{ chain {{ id }} }} }}
      }}
    }}"""
    items = gql(q)["data"]["markets"]["items"]
    return {
        it["marketId"]: {"chainId": it["morphoBlue"]["chain"]["id"], "loanAssetAddress": it["loanAsset"]["address"]}
        for it in items
    }


def fetch_known_curators() -> list:
    q = "{ curators(first:200) { items { id name } } }"
    return gql(q)["data"]["curators"]["items"]


def build_name_matchers(curators: list) -> list:
    """For each known curator, build word-boundary regexes to match against
    vault names: the full curator name (any length -- a multi-word phrase
    match is specific enough to trust), and its first word alone (only if
    long enough not to be a generic false-positive risk)."""
    matchers = []
    for c in curators:
        name = c["name"]
        matchers.append((len(name), re.compile(r"\b" + re.escape(name.lower()) + r"\b"), c))
        first_word = re.split(r"\s+", name)[0].lower()
        if len(first_word) >= MIN_WORD_MATCH_LEN and first_word != name.lower():
            matchers.append((len(first_word), re.compile(r"\b" + re.escape(first_word) + r"\b"), c))
    matchers.sort(key=lambda t: t[0], reverse=True)  # try most specific (longest) pattern first
    return matchers


def match_curator_by_name(name: str, matchers: list):
    low = name.lower()
    for _, pattern, curator in matchers:
        if pattern.search(low):
            return curator
    return None


def curator_label(name: str, curator_names: list, matchers: list) -> tuple:
    """Returns (label, attribution): 'tagged', 'inferred-from-name', or 'unattributed'."""
    if curator_names:
        return ", ".join(curator_names), "tagged"
    match = match_curator_by_name(name, matchers)
    if match:
        return match["name"], "inferred-from-name"
    return f"(no curator match: {name})", "unattributed"


def fetch_top_suppliers(market_id: str) -> list:
    q = f"""{{
      marketPositions(first:{TOP_SUPPLIERS_PER_MARKET}, orderBy: SupplyShares, orderDirection: Desc,
                       where:{{marketUniqueKey_in:["{market_id}"]}}) {{
        items {{ user {{ address }} state {{ supplyAssetsUsd }} }}
      }}
    }}"""
    items = gql(q)["data"]["marketPositions"]["items"]
    return [
        {"address": it["user"]["address"], "usd": it["state"]["supplyAssetsUsd"] or 0.0}
        for it in items
        if (it["state"]["supplyAssetsUsd"] or 0.0) > 0
    ]


def fetch_v1_vaults_by_address(addresses: list) -> dict:
    """address.lower() -> {'name', 'curators': [names]}"""
    if not addresses:
        return {}
    addr_list = ",".join(f'"{a}"' for a in addresses)
    q = f"""{{
      vaults(first:{len(addresses)}, where:{{address_in:[{addr_list}]}}) {{
        items {{ name address state {{ curators {{ name }} }} }}
      }}
    }}"""
    items = gql(q)["data"]["vaults"]["items"]
    return {
        v["address"].lower(): {"name": v["name"], "curators": [c["name"] for c in (v["state"]["curators"] or [])]}
        for v in items
    }


def fetch_v2_adapter_map(chain_id: int, asset_address: str) -> dict:
    """adapterAddress.lower() -> {'name' (owning vault), 'curators': [names]}. Paginates
    all VaultV2s for this (chain, asset) and reads each one's adapters."""
    adapter_map = {}
    skip, page_size = 0, 25
    while True:
        q = f"""{{
          vaultV2s(first:{page_size}, skip:{skip}, where:{{chainId_in:[{chain_id}], assetAddress_in:["{asset_address}"]}}) {{
            pageInfo {{ countTotal }}
            items {{
              name
              curators(first:5) {{ items {{ name }} }}
              adapters(first:10) {{ items {{ address }} }}
            }}
          }}
        }}"""
        data = gql(q)["data"]["vaultV2s"]
        for v in data["items"]:
            curator_names = [c["name"] for c in v["curators"]["items"]]
            for a in v["adapters"]["items"]:
                adapter_map[a["address"].lower()] = {"name": v["name"], "curators": curator_names}
        skip += page_size
        if skip >= data["pageInfo"]["countTotal"]:
            break
    return adapter_map


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--markets",
        default=str(DEFAULT_MARKETS_PATH),
        help=f"morpho_chronicle_history.json (or any {{marketId: {{...}}}}-shaped file) "
        f"to source Chronicle markets from (default: {DEFAULT_MARKETS_PATH})",
    )
    parser.add_argument(
        "--json", default=str(DEFAULT_JSON_PATH), help=f"write full breakdown to this JSON file (default: {DEFAULT_JSON_PATH})"
    )
    parser.add_argument(
        "--csv", default=str(DEFAULT_CSV_PATH), help=f"write the per-supplier breakdown to this CSV file (default: {DEFAULT_CSV_PATH})"
    )
    parser.add_argument(
        "--overview-csv",
        default=str(DEFAULT_OVERVIEW_CSV_PATH),
        help=f"write the human-readable curator x chain totals overview to this CSV file (default: {DEFAULT_OVERVIEW_CSV_PATH})",
    )
    parser.add_argument(
        "--total-json",
        default=str(DEFAULT_TOTAL_PATH),
        help=f"write the standard cross-protocol total file to this path (default: {DEFAULT_TOTAL_PATH})",
    )
    parser.add_argument("--no-output", action="store_true", help="skip writing --json/--csv files")
    args = parser.parse_args()
    if args.no_output:
        args.json = None
        args.csv = None
        args.overview_csv = None
        args.total_json = None

    markets = load_chronicle_markets(Path(args.markets))
    print(f"Tracing curator allocations for {len(markets)} Chronicle market(s)...", file=sys.stderr)

    chain_and_asset = fetch_market_chain_and_asset([m["marketId"] for m in markets])

    known_curators = fetch_known_curators()
    matchers = build_name_matchers(known_curators)
    print(f"Matching untagged vaults against {len(known_curators)} known curator names...", file=sys.stderr)

    v2_adapter_cache = {}  # (chainId, assetAddress) -> adapter_map

    def v2_adapters_for(chain_id, asset_address):
        key = (chain_id, asset_address.lower())
        if key not in v2_adapter_cache:
            v2_adapter_cache[key] = fetch_v2_adapter_map(chain_id, asset_address)
        return v2_adapter_cache[key]

    per_market = []
    curator_totals = {}  # label -> {"usd","usdTagged","usdInferred","usdUnattributed","markets","vaults","byChain"}
    unidentified_total = 0.0
    unidentified_by_chain = {}
    dust_total = 0.0
    dust_by_chain = {}

    for m in markets:
        meta = chain_and_asset[m["marketId"]]
        suppliers = fetch_top_suppliers(m["marketId"])
        v1_map = fetch_v1_vaults_by_address([s["address"] for s in suppliers])
        v2_map = v2_adapters_for(meta["chainId"], meta["loanAssetAddress"])

        rows = []
        covered = 0.0
        for s in suppliers:
            addr_low = s["address"].lower()
            if addr_low in v1_map:
                src = v1_map[addr_low]
                kind = "vault-v1"
            elif addr_low in v2_map:
                src = v2_map[addr_low]
                kind = "vault-v2-adapter"
            else:
                rows.append({"kind": "unidentified", "address": s["address"], "curator": None, "attribution": None, "usd": s["usd"]})
                unidentified_total += s["usd"]
                unidentified_by_chain[m["chain"]] = unidentified_by_chain.get(m["chain"], 0.0) + s["usd"]
                covered += s["usd"]
                continue

            label, attribution = curator_label(src["name"], src["curators"], matchers)
            rows.append(
                {
                    "kind": kind,
                    "address": s["address"],
                    "vault": src["name"],
                    "curator": label,
                    "attribution": attribution,
                    "usd": s["usd"],
                }
            )
            covered += s["usd"]

            bucket = curator_totals.setdefault(
                label,
                {"usd": 0.0, "usdTagged": 0.0, "usdInferred": 0.0, "usdUnattributed": 0.0, "markets": set(), "vaults": set(), "byChain": {}},
            )
            bucket["usd"] += s["usd"]
            bucket[{"tagged": "usdTagged", "inferred-from-name": "usdInferred", "unattributed": "usdUnattributed"}[attribution]] += s["usd"]
            bucket["markets"].add(m["pair"] + " (" + m["chain"] + ")")
            bucket["vaults"].add(src["name"])
            bucket["byChain"][m["chain"]] = bucket["byChain"].get(m["chain"], 0.0) + s["usd"]

        dust = max(m["valueUsd"] - covered, 0.0)
        dust_total += dust
        dust_by_chain[m["chain"]] = dust_by_chain.get(m["chain"], 0.0) + dust
        rows.sort(key=lambda r: r["usd"], reverse=True)
        per_market.append(
            {
                "pair": m["pair"],
                "chain": m["chain"],
                "marketId": m["marketId"],
                "valueUsd": m["valueUsd"],
                "url": m["url"],
                "suppliers": rows,
                "dustUsd": dust,  # long tail beyond the top TOP_SUPPLIERS_PER_MARKET positions fetched
            }
        )

    print(f"\n{'Market':24s} {'Chain':12s} {'Curator / address':44s} {'USD':>16s}")
    print("-" * 100)
    for pm in per_market:
        for r in pm["suppliers"]:
            if r["kind"] == "unidentified":
                print(f"{pm['pair']:24s} {pm['chain']:12s} {'(unidentified: ' + r['address'] + ')':44s} {r['usd']:>16,.2f}")
            else:
                mark = "~" if r["attribution"] == "inferred-from-name" else " "
                print(f"{pm['pair']:24s} {pm['chain']:12s} {mark}{r['curator']:43s} {r['usd']:>16,.2f}")
        if pm["dustUsd"] > 0.01:
            print(f"{pm['pair']:24s} {pm['chain']:12s} {'(long tail, uncovered)':44s} {pm['dustUsd']:>16,.2f}")
    print("(~ = curator inferred by matching vault name, not formally tagged in Morpho's registry)")

    print(f"\n{'Curator':34s} {'Total (USD)':>16s}  Markets / Vaults")
    print("-" * 100)
    ranked = sorted(curator_totals.items(), key=lambda kv: kv[1]["usd"], reverse=True)
    for label, bucket in ranked:
        note = f"  (~${bucket['usdInferred']:,.2f} inferred from vault name)" if bucket["usdInferred"] > 0 else ""
        print(f"{label:34s} {bucket['usd']:>16,.2f}  {len(bucket['markets'])} market(s) / {len(bucket['vaults'])} vault(s){note}")
    print(f"{'(unidentified addresses)':34s} {unidentified_total:>16,.2f}")
    print(f"{'(long tail, uncovered)':34s} {dust_total:>16,.2f}")

    grand_total = sum(b["usd"] for _, b in ranked) + unidentified_total + dust_total
    print(f"\n{'Grand total (all Chronicle markets):':34s} ${grand_total:,.2f}")

    # Final output: curator x chain matrix, then per-curator total, then grand total.
    all_chains = sorted({pm["chain"] for pm in per_market})
    matrix_rows = [(label, b["byChain"], b["usd"]) for label, b in ranked]
    if unidentified_total > 0:
        matrix_rows.append(("(unidentified addresses)", unidentified_by_chain, unidentified_total))
    if dust_total > 0:
        matrix_rows.append(("(long tail, uncovered)", dust_by_chain, dust_total))
    matrix_rows.sort(key=lambda r: r[2], reverse=True)

    label_w = 36
    col_w = 16
    print("\n\n=== FINAL OUTPUT: curator/protocol totals by chain (Morpho) ===")
    header = f"{'Curator / protocol':{label_w}s}" + "".join(f"{c:>{col_w}s}" for c in all_chains) + f"{'TOTAL':>{col_w}s}"
    print(header)
    print("-" * len(header))
    chain_grand = {c: 0.0 for c in all_chains}
    for label, by_chain, total in matrix_rows:
        for c in all_chains:
            chain_grand[c] += by_chain.get(c, 0.0)
        print(f"{label[:label_w]:{label_w}s}" + "".join(f"{by_chain.get(c, 0.0):>{col_w},.2f}" for c in all_chains) + f"{total:>{col_w},.2f}")
    print("-" * len(header))
    print(f"{'TOTAL':{label_w}s}" + "".join(f"{chain_grand[c]:>{col_w},.2f}" for c in all_chains) + f"{grand_total:>{col_w},.2f}")

    if args.overview_csv:
        import csv

        MIN_ROW_USD = 10.0  # curators/buckets below this are dust, not worth a row
        MIN_CELL_USD = 10.0  # same threshold for an individual chain's value within a kept row

        with open(args.overview_csv, "w", newline="") as fh:
            writer = csv.writer(fh)
            writer.writerow(["curator"] + all_chains + ["total"])
            for label, by_chain, total in matrix_rows:
                if total < MIN_ROW_USD:
                    continue
                cells = [f"{by_chain.get(c, 0.0):.2f}" if by_chain.get(c, 0.0) >= MIN_CELL_USD else "" for c in all_chains]
                writer.writerow([label] + cells + [f"{total:.2f}"])
            writer.writerow(["TOTAL"] + [f"{chain_grand[c]:.2f}" for c in all_chains] + [f"{grand_total:.2f}"])
        print(f"Wrote {args.overview_csv}", file=sys.stderr)

    if args.total_json:
        with open(args.total_json, "w") as fh:
            json.dump(
                {
                    "protocol": "Morpho",
                    "totalUsd": round(grand_total, 2),
                    "generatedAt": datetime.now(timezone.utc).isoformat(),
                    "breakdownFile": Path(args.overview_csv).name if args.overview_csv else None,
                },
                fh,
                indent=2,
            )
        print(f"Wrote {args.total_json}", file=sys.stderr)

    if args.json:
        with open(args.json, "w") as fh:
            json.dump(
                {
                    "perMarket": per_market,
                    "curatorTotals": {
                        label: {
                            "totalUsd": b["usd"],
                            "taggedUsd": b["usdTagged"],
                            "inferredFromNameUsd": b["usdInferred"],
                            "unattributedUsd": b["usdUnattributed"],
                            "byChain": b["byChain"],
                            "markets": sorted(b["markets"]),
                            "vaults": sorted(b["vaults"]),
                        }
                        for label, b in ranked
                    },
                    "unidentifiedUsd": unidentified_total,
                    "unidentifiedByChain": unidentified_by_chain,
                    "dustUsd": dust_total,
                    "dustByChain": dust_by_chain,
                    "grandTotalUsd": grand_total,
                    "finalOutput": {
                        "chains": all_chains,
                        "rows": [{"label": label, "byChain": by_chain, "totalUsd": total} for label, by_chain, total in matrix_rows],
                        "chainTotals": chain_grand,
                        "grandTotalUsd": grand_total,
                    },
                },
                fh,
                indent=2,
            )
        print(f"\nWrote {args.json}", file=sys.stderr)

    if args.csv:
        import csv

        with open(args.csv, "w", newline="") as fh:
            writer = csv.writer(fh)
            writer.writerow(["pair", "chain", "kind", "curator", "attribution", "vault", "address", "usd"])
            for pm in per_market:
                for r in pm["suppliers"]:
                    writer.writerow(
                        [
                            pm["pair"],
                            pm["chain"],
                            r["kind"],
                            r["curator"] or "",
                            r["attribution"] or "",
                            r.get("vault", ""),
                            r["address"],
                            f"{r['usd']:.2f}",
                        ]
                    )
                if pm["dustUsd"] > 0.01:
                    writer.writerow([pm["pair"], pm["chain"], "long-tail-uncovered", "", "", "", "", f"{pm['dustUsd']:.2f}"])
        print(f"Wrote {args.csv}", file=sys.stderr)


if __name__ == "__main__":
    main()
